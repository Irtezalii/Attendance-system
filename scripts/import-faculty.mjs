#!/usr/bin/env node
// Imports faculty directory profiles (data/faculty/*.json) into D1.
//
//   node scripts/import-faculty.mjs data/faculty/ubit-cs-directory.json --out .wrangler/seed/faculty.sql
//   npx wrangler d1 execute attendance-db --local --file .wrangler/seed/faculty.sql
//
// Profiles only: this never creates login accounts. Use scripts/grant-faculty-access.mjs
// to give a specific person access. Upserts on the stable "key" of each entry; directory
// fields are refreshed on re-run, while access-related fields (user_id, employee_id,
// status) are left as they are.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";

const CATEGORIES = new Set(["full_time", "teaching_associate", "visiting", "inter_departmental", "compulsory_subjects"]);
const DEFAULT_DEPARTMENT = "Department of Computer Science";

const args = process.argv.slice(2);
const outIndex = args.indexOf("--out");
const outPath = outIndex >= 0 ? args[outIndex + 1] : undefined;
const dataPath = args.find((a, i) => !a.startsWith("--") && i !== outIndex + 1);
if (!dataPath || !outPath) fail("usage: node scripts/import-faculty.mjs <directory.json> --out <file.sql>");

function fail(message) {
  console.error(`import-faculty: ${message}`);
  process.exit(1);
}

function sql(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replaceAll("'", "''")}'`;
}

const tidy = (v) => (v === null || v === undefined ? null : String(v).replace(/\s+/g, " ").trim() || null);

const data = JSON.parse(readFileSync(dataPath, "utf8"));
const seen = new Set();
const out = [`-- Generated by scripts/import-faculty.mjs from ${dataPath}. Safe to re-run. Creates no login accounts.`];

for (const f of data.faculty ?? []) {
  if (!/^[a-z0-9-]+$/.test(f.key ?? "")) fail(`invalid key "${f.key}"`);
  if (seen.has(f.key)) fail(`duplicate key "${f.key}"`);
  seen.add(f.key);
  if (!tidy(f.name)) fail(`${f.key}: name is required`);
  if (!CATEGORIES.has(f.category)) fail(`${f.key}: unknown category "${f.category}"`);
  if (f.email && !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(f.email)) fail(`${f.key}: invalid email "${f.email}"`);

  const columns = {
    directory_key: f.key,
    name: tidy(f.name),
    designation: tidy(f.designation),
    department: tidy(f.department) ?? DEFAULT_DEPARTMENT,
    category: f.category,
    email: f.email ? f.email.trim().toLowerCase() : null,
    qualifications: tidy(f.qualifications),
    research_interests: tidy(f.researchInterests),
    directory_notes: tidy(f.notes),
    profile_url: tidy(f.profileUrl),
    image_url: tidy(f.imageUrl),
    source_url: data.source?.url ?? null,
    verified_on: data.source?.retrievedOn ?? null,
  };
  const names = Object.keys(columns);
  out.push(
    `INSERT INTO faculty (${names.join(", ")}) VALUES (${names.map((n) => sql(columns[n])).join(", ")})
       ON CONFLICT (directory_key) DO UPDATE SET ${names.filter((n) => n !== "directory_key").map((n) => `${n} = excluded.${n}`).join(", ")};`,
  );
}

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out.join("\n") + "\n");
console.log(`import-faculty: wrote ${seen.size} profiles to ${outPath}`);
